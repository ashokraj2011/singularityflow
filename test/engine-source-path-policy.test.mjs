// Captured by the native implementation before extraction, not generated by these rules.
const baseline=JSON.parse(await readFile(new URL('./fixtures/source-path-policy-packets/native-v1.json',import.meta.url),'utf8'));
const digest=value=>createHash('sha256').update(value).digest('hex');
const outcome=invoke=>{
  let result;
  try{result={value:invoke()};}catch(error){result={error:{name:error.name,message:error.message,code:error.code??null,details:error.details??null}};}
  return JSON.parse(JSON.stringify(result));
};
const syntax=grammar=>Object.freeze({profile:CONFIGURATION_PATH_SYNTAX,grammar:grammar.sep==='\\'?'win32':'posix',
  isAbsolute:grammar.isAbsolute,normalize:grammar.normalize,parse:grammar.parse,
  posixIsAbsolute:path.posix.isAbsolute,posixNormalize:path.posix.normalize,posixBasename:path.posix.basename,
  toPosix:value=>value.split(grammar.sep).join('/')});
function families(port){
  return {configuration:rules.configurationFilePolicies(port),boundary:rules.sourceBoundaryPolicies(port),
    supporting:rules.supportingChangePolicies(port),application:rules.applicationPathPolicies(GOVERNED_ROOTS),
    repository:rules.changeScopePolicies(port),delivery:rules.deliveryClassificationPolicies(port,GOVERNED_ROOTS)};
}

