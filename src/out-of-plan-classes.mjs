/**
 * A change outside the plan: which files SFlow settles itself, with an undo, and which go to a person [owner, 2026-11-19, C3].
 *
 * An allowlist: a file is settled only when it falls in one of these classes, and every other file is a person's question.
 * Settling never changes a file; it records where the file belongs in the plan, with the evidence it rests on.
 *
 *   companion       a file beside one an approved row names, same folder and same name before the first dot, when only one
 *                   row of the step names one (`Pricing.module.css` beside `Pricing.tsx`): added to that row
 *   test-support    a mock, fixture, setup, helper or page object, by its path (supporting-changes.mjs), by the folder the
 *                   repository's own test runner configuration names, or by its content (it imports a browser test library and
 *                   only tests import it; test-support-detection.mjs). Never by its name alone: `src/pages/HomePage.tsx` is
 *                   product code. Listed as a supporting change
 *   documentation   Markdown, reStructuredText, AsciiDoc or text at the root or under docs/: listed as a supporting change
 *   ignore-file     .gitignore, .dockerignore, .npmignore, .prettierignore, .eslintignore: listed as a supporting change
 *   generated       a file that says it is generated in its first lines (or that .gitattributes marks linguist-generated)
 *                   whose source beside it is planned or settled: added to its source's row
 *
 * A person is always asked, even inside those classes, for a protected path, a secret-shaped or always-local file, a path
 * the quick-fix policy holds sensitive (with `infra`), a migration or runtime configuration, a file a person rejected or
 * undid, a file that already has an open departure, and a class that rests on a declaration this Story itself changed.
 *
 * Never settled, each with its own words on the card: a new or changed dependency (manifests and lock files), how the
 * product is built, shipped or tested (build, CI and test-runner configuration), who governs the repository (CODEOWNERS,
 * .gitattributes, dependabot, renovate, PR and issue templates, editor tasks), and anything that can change what the
 * product does. Pure: what a file holds arrives from the caller.
 */
import path from 'node:path';

import { IGNORE_FILES, personClass } from './person-change-class.mjs';
import { classifySupportingChange } from './supporting-changes.mjs';

export { personClass };

export const SETTLE_CLASSES = Object.freeze(['companion', 'test-support', 'documentation', 'ignore-file', 'generated']);
export const PERSON_CLASSES = Object.freeze(['dependency', 'build', 'governance', 'behaviour', 'sensitive']);

// The quick-fix policy's prohibited paths (DEFAULT_QUICK_FIX_POLICY in quick-fix-policy.mjs, which a test holds equal), and
// `infra` beside `infrastructure`. Kept here so settling loads no Git or plan reader.
export const SENSITIVE_PATH_PATTERNS = Object.freeze([
  /(^|\/)(api|apis|schema|schemas|migration|migrations|security|auth|deploy|deployment|infrastructure|infra|terraform)(\/|$)/i,
  /(^|\/)(openapi|asyncapi|dockerfile|helm|k8s)(\.|\/|$)/i
]);
const SECRET = /(?:^|\/)(?:\.env(?:\..*)?|id_(?:rsa|ed25519|ecdsa)|[^/]+\.(?:pem|key|p12|pfx|keystore|jks))$/iu;
// First lines that say a file is generated (Go, Bazel, protoc, .NET and the common @generated marker).
const GENERATED_MARKER = /@generated\b|\bCode generated\b.*\bDO NOT EDIT\b|<auto-generated/u;

const stem = (file) => path.posix.basename(file).split('.')[0];
const inside = (file, entry) => file === entry || file.startsWith(`${entry}/`);

/** The one row of `phase` that names a companion of `file`, with that path; null when none or several do. */
export function coveringRow(plan, phaseId, file) {
  const folder = path.posix.dirname(file);
  const name = stem(file);
  if (!name) return null;
  const rows = Object.entries(plan ?? {}).filter(([, claim]) => (!(claim.steps ?? []).length || claim.steps.includes(phaseId)) && claim.fulfillment !== 'test-only')
    .map(([clauseId, claim]) => ({ clauseId, path: (claim.expectedPaths ?? []).find((entry) => entry !== file && path.posix.dirname(entry) === folder && stem(entry) === name) }))
    .filter((row) => row.path);
  return new Set(rows.map((row) => row.clauseId)).size === 1 ? rows[0] : null;
}

/** Whether a path is one the quick-fix policy holds sensitive (with `infra`). */
export const sensitivePath = (file) => SENSITIVE_PATH_PATTERNS.some((pattern) => pattern.test(file));

/** Why a person is asked even inside a settle class, in words; null when nothing holds it. */
function veto(file, { protectedPaths = [], rejected = new Set(), undone = new Set(), open = new Set(), alwaysLocal = () => false }) {
  if (SECRET.test(file) || alwaysLocal(file)) return 'it is shaped like a secret or an environment file';
  if (protectedPaths.some((entry) => inside(file, String(entry).replace(/\/$/u, '')))) return 'it is a protected path';
  if (sensitivePath(file)) return 'its path is one a quick fix may not touch (an interface, schema, migration, security, deployment or infrastructure path)';
  const refused = classifySupportingChange(file).refused;
  if (refused === 'migration' || refused === 'configuration') return refused === 'migration' ? 'it is a migration' : 'it is runtime configuration';
  if (rejected.has(file)) return 'a person rejected it';
  if (undone.has(file)) return 'a person undid its settlement, so it is theirs to answer';
  if (open.has(file)) return 'it already waits for a person as a departure';
  return null;
}

/**
 * Where one changed file outside the plan belongs: `{ settle: { class, answer, evidence, effect } }` when SFlow settles it,
 * or `{ person: { class, words } }`. `context`:
 *   plan, phaseId         the approved plan's merged rows and the step
 *   protectedPaths, rejected, undone, open   the vetoes above
 *   testSupport           Map of a file to the evidence that it is test support by the repository's own test configuration
 *                         or by its content (test-support-detection.mjs), already without any declaration this Story changed
 *   head(file)            its first lines, for the generated marker; `generatedPaths` the files .gitattributes marks at the base
 *   settledRows           Map of a settled or planned file to its row, for a generated file's source
 *   reason                the agent's own words, when it recorded the file itself: one more line of evidence
 */
export function outOfPlanPlace(file, context = {}) {
  const { plan = {}, phaseId = null, testSupport = new Map(), head = () => null, generatedPaths = new Set(), settledRows = new Map(), reason = null } = context;
  const held = veto(file, context);
  if (held) return { person: { class: 'sensitive', words: `SFlow does not settle it: ${held}. A person decides it.` } };
  const named = personClass(file);
  if (named) return { person: named };
  const agent = reason ? [{ what: `the agent says: ${String(reason).replace(/\s+/gu, ' ').trim()}`, where: 'its departure record' }] : [];
  const supporting = (cls, how, line) => ({ settle: { class: cls, answer: `Listed ${file} in the plan as a supporting change (${how}): it serves the change, not one requirement.`,
    evidence: [line, ...agent], effect: { file, class: cls === 'ignore-file' ? 'repository-metadata' : cls === 'documentation' ? 'documentation' : 'test-support',
      ...(cls === 'test-support' && testSupport.has(file) ? { rule: testSupport.get(file).rule } : {}) } } });
  const base = path.posix.basename(file).toLowerCase();
  if (IGNORE_FILES.has(base)) return supporting('ignore-file', 'an ignore file', { what: `${file} only lists files a tool leaves out`, where: file });
  const classified = classifySupportingChange(file).class;
  if (classified === 'documentation') return supporting('documentation', 'documentation', { what: `${file} is documentation`, where: path.posix.dirname(file) === '.' ? 'the repository root' : path.posix.dirname(file) });
  if (classified === 'test-support') return supporting('test-support', 'test support', { what: `${file} is test support by where it is (a mock, fixture, setup or helper of the tests)`, where: path.posix.dirname(file) });
  if (testSupport.has(file)) {
    const found = testSupport.get(file);
    return { settle: { class: 'test-support', answer: `Listed ${file} in the plan as a supporting change (test support): ${found.rule === 'test-root' ? 'the repository\'s own test configuration names its folder' : 'only tests use it'}.`,
      evidence: [...found.evidence, ...agent].slice(0, 8), effect: { file, class: 'test-support', rule: found.rule } } };
  }
  const row = coveringRow(plan, phaseId, file);
  if (row) {
    return { settle: { class: 'companion', answer: `Accounted ${file} to ${row.clauseId}'s row, which names ${row.path} beside it.`,
      evidence: [{ what: `${row.clauseId}'s row names ${row.path}`, where: 'the approved plan' },
        { what: `${file} sits beside it with the same name`, where: path.posix.dirname(file) },
        { what: `no other row of ${phaseId} names a file of that name there`, where: 'the approved plan' }, ...agent],
      effect: { clauseId: row.clauseId, path: file } } };
  }
  const marked = generatedPaths.has(file) ? '.gitattributes marks it linguist-generated'
    : GENERATED_MARKER.test(String(head(file) ?? '').split(/\r?\n/u).slice(0, 5).join('\n')) ? 'its first lines say it is generated' : null;
  if (marked) {
    const source = [...settledRows.entries()].find(([entry]) => entry !== file && path.posix.dirname(entry) === path.posix.dirname(file) && stem(entry) === stem(file));
    if (source) {
      const [from, clauseId] = source;
      return { settle: { class: 'generated', answer: `Accounted ${file} to ${clauseId}'s row: it is generated from ${from}, which that row holds.`,
        evidence: [{ what: marked, where: file }, { what: `its source ${from} is in ${clauseId}'s row`, where: 'the approved plan' }, ...agent],
        effect: { clauseId, path: file } } };
    }
  }
  return { person: { class: 'behaviour', words: 'It can change what the product does, and no row of the plan names it, so a person decides it.' } };
}
