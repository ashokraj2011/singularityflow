test('all 31 original rule bodies keep their independent native fingerprints',async()=>{
  const owner='src/kernel/source-path-policies.mjs';
  const ast=ts.createSourceFile(owner,await readFile(new URL('../'+owner,import.meta.url),'utf8'),ts.ScriptTarget.Latest,true);
  const printer=ts.createPrinter({removeComments:false}),seen=new Set();
  const names=new Map(Object.entries(baseline.functions).map(([key,hash])=>[key.split('.').at(-1),{key,hash}]));
  const visit=node=>{
    if(ts.isFunctionDeclaration(node)&&node.name&&names.has(node.name.text)){
      const {key,hash}=names.get(node.name.text);
      assert.equal(digest(printer.printNode(ts.EmitHint.Unspecified,node.body,ast)),hash,key);
      seen.add(key);
    }
    ts.forEachChild(node,visit);
  };
  visit(ast);
  assert.deepEqual([...seen].sort(),Object.keys(baseline.functions).sort());
});

