import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { operationCatalog, validateOperationRegistry } from '../src/command-registry.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'docs', 'OPERATION-MODEL-POLICY.md');
const write = process.argv.includes('--write');

validateOperationRegistry();

function cell(value) { return value == null ? '—' : String(value).replaceAll('|', '\\|'); }

const rows = operationCatalog().map((entry) => [
  entry.id,
  entry.classification,
  entry.modelPolicy,
  entry.fallback?.operationId ?? '—',
  entry.externalDependencies.join(', ') || '—'
]);
const content = `${[
  '# Operation Model Policy Catalog',
  '',
  '> Generated by `npm run operation-catalog:generate`. Do not edit by hand.',
  '',
  'Every public operation is classified before its implementation module is imported. `never` operations cannot cross the kernel model boundary; `required` operations fail fast when model mode is disabled.',
  '',
  '| Operation | Class | Model policy | Guided fallback | External dependencies |',
  '|---|---|---|---|---|',
  ...rows.map((row) => `| ${row.map(cell).join(' | ')} |`)
].join('\n')}\n`;

if (write) {
  await writeFile(target, content, 'utf8');
  console.log(`Wrote ${path.relative(root, target)}.`);
} else {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== content) {
    console.error('Operation model-policy catalog is stale. Run npm run operation-catalog:generate.');
    process.exitCode = 1;
  } else console.log('Operation model-policy catalog is current.');
}
