import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import YAML from 'yaml';
import { normalizeApprovalAuthorities } from '../src/approval-authority.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const workflow = YAML.parse(await readFile(path.join(root, 'templates/workflow.yml'), 'utf8'));
const portfolio = YAML.parse(await readFile(path.join(root, 'templates/portfolio.yml'), 'utf8'));
const workflowAuthorities = normalizeApprovalAuthorities(workflow.approvalAuthorities);
const portfolioAuthorities = portfolio.approvalAuthorities ?? {};
const teams = [...new Set([
  ...Object.values(workflowAuthorities).flatMap((authority) => authority.githubTeams ?? []),
  ...Object.values(portfolioAuthorities).flatMap((authority) => authority.githubTeams ?? [])
])].sort();
const owners = teams.join(' ');
const lines = [
  '# Generated by scripts/generate-codeowners.mjs from approvalAuthorities.githubTeams.',
  '# Governed agents never appear here because they are prompt contracts, not approval authorities.',
  ''
];
if (owners) {
  lines.push(
    `/ledger/** ${owners}`,
    `/singularity/workflow.yml ${owners}`,
    `/singularity/portfolio.yml ${owners}`,
    `/singularity/capabilities.yml ${owners}`,
    `/plugin/** ${owners}`,
    `/scripts/generate-codeowners.mjs ${owners}`
  );
} else {
  lines.push('# No GitHub teams are configured in the editable starter authority groups.');
}
const expected = `${lines.join('\n')}\n`;
const target = path.join(root, '.github', 'CODEOWNERS');
if (process.argv.includes('--write')) {
  await writeFile(target, expected);
  process.stdout.write(`Wrote ${path.relative(root, target)} for ${teams.length} authority team(s).\n`);
} else {
  const current = existsSync(target) ? await readFile(target, 'utf8') : '';
  if (current !== expected) {
    process.stderr.write('CODEOWNERS is stale. Run npm run codeowners:generate.\n');
    process.exitCode = 1;
  }
}
