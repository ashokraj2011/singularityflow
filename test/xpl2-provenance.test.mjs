const GENERATION = { subject: 'generation', phase: 'implementation', generation: 2 };

function lineView(fixture, input, query) {
  const request = xpl2LineHistoryRequest({ codeExplanation: input.codeExplanation, diff: fixture.diff ?? null, context: input.context }, query);
  const result = request?.kind === 'baseline' ? lineCommitAt(fixture.root, request.revision, request.path, request.line) : null;
  return explainXpl2Subject(input, query, { lineHistory: { request, result } });
}

/** One invocation through the real runner, recorded for the Story's implementation generation 2. */
function invoke(root, text = 'ok') {
  return withOperationContext({
    operation: { id: 'model.test', modelPolicy: 'required' }, modelMode: { enabled: true }, root, command: 'test'
  }, () => invokeModel({
    provider: 'copilot-cli',
    providerConfig: { executable: process.execPath, arguments: ['-e', `process.stdout.write(${JSON.stringify(text)})`, '--'], promptTransport: 'attachment' },
    cwd: root, allowedRoots: [root], auditRoot: root, channel: 'test', prompt: { text: 'write the export filter' },
    subject: { kind: 'story', id: 'ORD-418', phase: 'implementation', generation: 2 },
    tools: { mode: 'none', names: [] }, limits: { timeoutMs: 5000, outputBytes: 1024 }
  }));
}

const texts = (model) => [...model.statements, ...model.derived].map((entry) => entry.text).join('\n');

test('XPL2-AC-011 a line changed in several invocations and then by a person has no inferred origin', async (t) => {
  const fixture = await createXpl2Fixture(t);
  await invoke(fixture.root);
  await invoke(fixture.root);
  // A person then edits the same line again in the working tree.
  const file = path.join(fixture.root, 'src/export/service.ts');
  const lines = (await readFile(file, 'utf8')).split('\n');
  lines[4] = '  const step5 = range.start ?? 0;';
  await writeFile(file, lines.join('\n'));
  const { input, diff } = await xpl2InputFor(fixture.root, fixture.base, {
    workflow: fixture.workflow, clauseSources: fixture.clauseSources, replay: fixture.replay
  });
  const line = lineView({ ...fixture, diff }, input, { subject: 'line', path: 'src/export/service.ts', line: 5 });
  assert.match(texts(line), /After-side line 5 of src\/export\/service\.ts was added or changed in H-\d{3} of this captured change, after the baseline; the baseline's commit history does not record it/u);
  const provenance = line.derived.find((entry) => entry.template === 'xpl2.provenance-unavailable@1');
  assert.match(provenance.text, /No admitted record establishes who or what produced this content\./u);
  assert.deepEqual(provenance.limitations, []);
  assert.doesNotMatch(texts(line), /written by|authored by|generated by|invocation|model /iu, 'a line names no invocation or model');

  const sources = await readGenerationSources(fixture.root, fixture.workflow, { phase: 'implementation', generation: 2 });
  assert.equal(sources.invocations.records.length, 2);
  const generation = explainXpl2Subject(input, GENERATION, { generationSources: sources });
  const invocations = generation.derived.filter((entry) => entry.kind === 'generation-invocation');
  assert.equal(invocations.length, 2);
  for (const entry of invocations) assert.match(entry.text, /it does not say which files or lines it wrote\./u);
  assert.match(texts(generation), /Change provenance for implementation generation 2 is unavailable\. No admitted record establishes who or what produced this content\./u);
});

test('XPL2-AC-041 no view estimates a share of AI-written lines', async (t) => {
  const fixture = await createXpl2Fixture(t);
  await invoke(fixture.root);
  const sources = await readGenerationSources(fixture.root, fixture.workflow, { phase: 'implementation', generation: 2 });
  const views = [
    explainXpl2Subject(fixture.input, { subject: 'change' }),
    explainXpl2Subject(fixture.input, GENERATION, { generationSources: sources }),
    lineView(fixture, fixture.input, { subject: 'line', path: 'src/export/service.ts', line: 5 })
  ];
  for (const view of views) {
    assert.doesNotMatch(texts(view), /\d\s*%|percent|share of (?:the )?lines|AI-(?:written|authored|generated)/iu);
    for (const key of Object.keys(view.inventory.counts)) assert.doesNotMatch(key, /^(?:ai|model)|authored|percent|share/iu, key);
  }
});

test('XPL2-AC-042 concurrent invocations keep their IDs and order is not invented', async (t) => {
  const made = await createXpl2Fixture(t);
  const record = (id, startedAt, completedAt, calls = null) => ({
    id, status: completedAt ? 'completed' : 'started', requestedModel: 'auto', modelSelection: { providerSelectedModel: null },
    startedAt, completedAt, toolObservation: calls ? { calls: calls.map((sequence) => ({ sequence, name: 'view', status: 'completed' })) } : null,
    observationIntegrity: 'machine-local-mac'
  });
  {
    const records = [
      record('inv-late', '2026-10-01T10:06:00.000Z', '2026-10-01T10:07:00.000Z'),
      record('inv-sub', '2026-10-01T10:02:00.000Z', '2026-10-01T10:04:00.000Z', [1, 2, 3]),
      record('inv-root', '2026-10-01T10:00:00.000Z', '2026-10-01T10:05:00.000Z', [1])
    ];
    const generation = explainXpl2Subject(made.input, GENERATION, { generationSources: {
      invocations: { status: 'available', records, omitted: 0 }, prompts: null, attempts: null
    } });
    const listed = generation.derived.filter((entry) => entry.kind === 'generation-invocation').map((entry) => entry.arguments.invocationId);
    assert.deepEqual(listed, ['inv-root', 'inv-sub', 'inv-late'], 'listed by their own recorded start, not arrival order');
    const overlaps = generation.derived.filter((entry) => entry.kind === 'invocation-overlap');
    assert.deepEqual(overlaps.map((entry) => [entry.arguments.first, entry.arguments.second]), [['inv-root', 'inv-sub']]);
    assert.match(overlaps[0].text, /overlap in time; the records establish no order between them\./u);
    assert.match(texts(generation), /3 tool calls observed, in their recorded order/u);
    assert.doesNotMatch(texts(generation), /\b(?:caused|triggered|then wrote|before writing)\b/iu);
  }
});

test('XPL2-AC-043 prepared, handed-off, redacted, disabled and machine-local captures stay distinct; reading enables nothing', async (t) => {
  const fixture = await createXpl2Fixture(t);
  // Reading a fresh repository's records switches nothing on and creates no capture store.
  const before = await promptAuditStatus(fixture.root);
  assert.equal(before.enabled, false);
  await comprehensionSlice(fixture.root);
  const off = await readGenerationSources(fixture.root, fixture.workflow, { phase: 'implementation', generation: 2 });
  assert.equal((await promptAuditStatus(fixture.root)).enabled, false, 'opening a view enables no recording');
  await assert.rejects(access(path.join(fixture.root, '.git', 'singularity-flow', 'model-invocations')));
  const offView = explainXpl2Subject(fixture.input, GENERATION, { generationSources: off });
  assert.match(texts(offView), /The prompt log on this machine is off: 0 records for this generation\. Recording for this source is disabled by its owner\./u);
  assert.match(texts(offView), /The model invocation record on this machine is readable: 0 records for this generation\. Only records kept on this machine are visible/u);

  await setPromptAudit(fixture.root, true);
  const base = { workId: 'ORD-418', phase: 'implementation', generation: 2, agent: 'developer' };
  await recordPromptAudit(fixture.root, { ...base, source: 'wm-compose', prompt: 'prepared prompt' });
  await recordPromptAudit(fixture.root, { ...base, source: 'vscode-governed-handoff', prompt: 'handed prompt' });
  await recordPromptAudit(fixture.root, { ...base, source: 'vscode-governed-handoff', prompt: `token ghp_${'x'.repeat(36)} here` });
  await invoke(fixture.root);
  const on = await readGenerationSources(fixture.root, fixture.workflow, { phase: 'implementation', generation: 2 });
  const view = explainXpl2Subject(fixture.input, GENERATION, { generationSources: on });
  const prompts = view.derived.filter((entry) => entry.kind === 'generation-prompt').map((entry) => entry.text);
  assert.equal(prompts.length, 4);
  assert.ok(prompts.some((text) => /was composed and prepared; whether it was sent was not observed\.$/u.test(text)));
  assert.ok(prompts.some((text) => /was handed to the Copilot host; the host's own invocation was not observed\.$/u.test(text)));
  assert.ok(prompts.some((text) => /1 secret-shaped value was redacted before it was kept/u.test(text)));
  assert.ok(prompts.some((text) => /was sent through the model runner; it names invocation /u.test(text)));
  assert.match(texts(view), /The prompt log on this machine is readable \(it keeps \d+ days\): 4 records for this generation\. Only records kept on this machine are visible/u);
  // Prompt text never enters the view.
  assert.doesNotMatch(JSON.stringify(view), /prepared prompt|handed prompt|ghp_x|write the export filter/u);
});

test('XPL2-AC-044 missing events are not zero actions or a success', async (t) => {
  const fixture = await createXpl2Fixture(t);
  const generation = explainXpl2Subject(fixture.input, GENERATION, { generationSources: {
    invocations: { status: 'available', omitted: 0, records: [{
      id: 'inv-open', status: 'started', requestedModel: 'auto', startedAt: '2026-10-01T10:00:00.000Z', completedAt: null,
      toolObservation: null, observationIntegrity: 'unverified-local'
    }] },
    prompts: { status: 'available', enabled: false, retentionDays: 30, integrity: null, records: [], omitted: 0 },
    attempts: { status: 'inaccessible', records: [], omitted: 0 }
  } });
  const [invocation] = generation.derived.filter((entry) => entry.kind === 'generation-invocation');
  assert.match(invocation.text, /started and has no recorded outcome/u);
  assert.match(invocation.text, /with no recorded end; no tool observation was recorded/u);
  assert.ok(invocation.limitations.includes('outcome-unobserved'));
  const all = texts(generation);
  assert.doesNotMatch(all, /\b0 tool calls\b|no failures|succeeded|completed successfully/iu);
  assert.match(all, /The prompt log on this machine is off/u);
});

test('line history: ordinary commit attribution maps unchanged lines across deletions, and context is not change', async (t) => {
  const baseline = `${Array.from({ length: 30 }, (_, index) => `const v${index + 1} = ${index + 1};`).join('\n')}\n`;
  const lines = baseline.split('\n');
  lines.splice(9, 1);
  lines[19] = 'const v21 = 2100;';
  const repository = await createChangeRepository(t, { baseline: { 'app.js': baseline }, change: { 'app.js': lines.join('\n') } });
  const { input, diff } = await xpl2InputFor(repository.root, repository.base);
  const at = (line, side = 'after') => {
    const query = { subject: 'line', path: 'app.js', line, side };
    const request = xpl2LineHistoryRequest({ codeExplanation: input.codeExplanation, diff, context: input.context }, query);
    const result = request?.kind === 'baseline' ? lineCommitAt(repository.root, request.revision, request.path, request.line) : null;
    return { request, result, view: explainXpl2Subject(input, query, { lineHistory: { request, result } }) };
  };
  const outside = at(25);
  assert.equal(outside.request.placement, 'outside');
  assert.equal(outside.request.line, 26, 'one deleted line above shifts the baseline line by one');
  assert.equal(outside.result.originalLine, 26);
  assert.match(texts(outside.view), /After-side line 25 of app\.js is baseline line 26, outside the changed units, and was last changed in commit [0-9a-f]{12} \(“baseline”, recorded author XPL2 Fixture, /u);
  assert.match(texts(outside.view), /The author field is what the commit records; it does not show how the line was produced\./u);
  assert.equal(at(20).request.kind, 'captured-change', 'the changed line is not in the baseline history');
  const context = at(19);
  assert.equal(context.request.placement, 'context');
  assert.equal(context.request.line, 20);
  assert.match(texts(context.view), /is unchanged context inside a change unit \(baseline line 20\)/u);
  const deleted = at(10, 'before');
  assert.equal(deleted.request.line, 10);
  assert.match(texts(deleted.view), /Before-side line 10 of app\.js was last changed in commit/u);
  // A revision that is not an exact commit is never guessed at.
  const unknown = xpl2LineHistoryRequest({ codeExplanation: input.codeExplanation, diff, context: { base: 'HEAD' } },
    { subject: 'line', path: 'app.js', line: 25 });
  assert.deepEqual(unknown, { kind: 'unavailable', reason: 'source-not-recorded' });
  assert.equal(lineCommitAt(repository.root, 'HEAD', 'app.js', 1), null);
});

test('snapshot comparison names new, gone and unchanged units by full digest, and the banner says so', async (t) => {
  const fixture = await createXpl2Fixture(t);
  const older = explainXpl2Subject(fixture.input, { subject: 'change' });
  await writeFile(path.join(fixture.root, 'src/export/extra.ts'), 'export const extra = 1;\n');
  const { input } = await xpl2InputFor(fixture.root, fixture.base);
  const newer = explainXpl2Subject(input, { subject: 'change' });
  // Every unit digest is bound to its own snapshot; none is shared between the two views.
  const digests = new Set(older.inventory.units.map((unit) => unit.explanationUnitSha256));
  assert.ok(newer.inventory.units.every((unit) => !digests.has(unit.explanationUnitSha256)));
  const comparison = compareXpl2Views(older, newer);
  assert.equal(comparison.sameSet, false);
  assert.equal(comparison.units.addedCount, 1);
  assert.equal(comparison.units.added[0].path, 'src/export/extra.ts');
  assert.equal(comparison.units.removedCount, 0);
  assert.equal(comparison.units.kept, older.inventory.units.length);
  assert.ok(comparison.sources.changed.includes('SRC-MANIFEST'));
  // Equal display IDs are not equal changes: only the change content counts.
  const relabelled = structuredClone(newer);
  for (const unit of relabelled.inventory.units) unit.changeContentSha256 = `sha256:${'0'.repeat(63)}${unit.unitId.slice(-1)}`;
  assert.equal(compareXpl2Views(older, relabelled).units.kept, 0);
  assert.equal(compareXpl2Views(older, null), null);
  const html = renderExplorer(older, { newerSnapshot: true, newerView: newer });
  assert.match(html, /<strong>Snapshot changed\.<\/strong> The repository moved since this view was built\. Since this view: 1 change unit new, 0 gone, 6 unchanged; \d+ sources? changed \(/u);
  assert.match(html, /New changes in src\/export\/extra\.ts\./u);
  assert.doesNotMatch(html, /New changes in [^.]*[HO]-\d{3}/u, 'the newer view\'s display IDs are not shown against the older view');
  assert.match(html, /You are still looking at the earlier snapshot\./u);
});
