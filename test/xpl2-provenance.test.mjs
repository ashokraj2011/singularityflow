/**
 * XPL2 M3: line history and generation timelines over real local records.
 *
 * Model invocations are made through the real runner with a local stand-in executable (no provider
 * is called); prompt-log entries are written by the prompt log's own writer. The views must show
 * exactly what those records say: ordinary commit history for a line, invocations and prompts for
 * a generation, and never who or what wrote a line.
 */
import assert from 'node:assert/strict';
