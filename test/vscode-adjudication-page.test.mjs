/**
 * The convergence decisions on one page. The page never preselects an answer, Accept all reaches only
 * changed files, and every answer keeps its own reason.
 */
import assert from 'node:assert/strict';
import test from 'node:test';
import {
  ADJUDICATION_SCRIPT, adjudicationAnswersFrom, adjudicationDraftFrom, adjudicationHtml, adjudicationListFrom, adjudicationSummary
} from '../apps/vscode/src/views/adjudication-page.ts';

const item = (id, fields = {}) => ({ id, kind: 'unclaimed-changed-path', paths: [`src/${id}.js`], clauseIds: [], detail: null, plan: null, acceptAll: true, decision: null, ...fields });
const list = (fields = {}) => ({
  status: 'open', workId: 'PAY-1', phase: 'convergence', repositoryPath: '/repo', open: 3, digest: 'sha256:abc',
  items: [item('CF-1'), item('CF-2', { plan: { kind: 'supporting', class: 'test-setup', text: 'Test setup.' } }),
    item('CF-3', { kind: 'absent-observed-claim', acceptAll: false, paths: [], detail: 'No test proves REQ-001.', clauseIds: ['PAY-1:REQ-001'] })],
  decidedBy: { groups: ['leads'], labels: ['Leads'], allowed: true, words: 'You may decide these (Leads).' },
  dispositions: [{ id: 'accepted-deviation', label: 'Accept as is' }, { id: 'rework', label: 'Send back to fix' }, { id: 'update-intent', label: 'The spec should change' }],
  ...fields
});
const row = (id, disposition, reason = '', clauses = '') => ({ id, disposition, reason, clauses });

test('the page shows what changed, what the plan says, and preselects nothing', () => {
  const html = adjudicationHtml(list());
  assert.match(html, /What the plan already says/u);
  assert.match(html, /Supporting file: Test setup\./u);
  assert.match(html, /Not in the plan/u);
  assert.match(html, /No test proves REQ-001\./u);
  assert.doesNotMatch(html, /<option[^>]* selected/u, 'an answer was chosen for the person');
  assert.match(html, /Accept all 2 changed files with one reason/u, 'Accept all counted more than changed files');
});

test('someone outside the group reads the table and cannot record', () => {
  const html = adjudicationHtml(list({ decidedBy: { groups: ['leads'], labels: ['Leads'], allowed: false, words: 'The Leads decide these.' } }));
  assert.match(html, /The Leads decide these\./u);
  assert.match(html, /data-review disabled/u);
  assert.doesNotMatch(html, /data-accept-all>/u);
});

test('text from the repository cannot become markup', () => {
  const html = adjudicationHtml(list({ items: [item('CF-1', { paths: ['<img src=x onerror=alert(1)>.js'] })] }));
  assert.doesNotMatch(html, /<img/u);
});

test('each answer keeps its own reason, and rows left open stay undecided', () => {
  const { answers, problem } = adjudicationAnswersFrom(list(), { type: 'adjudicate.review', rows: [
    row('CF-1', 'accepted-deviation', ' Generated by the formatter. '), row('CF-2', 'rework'), row('CF-3', '')] });
  assert.equal(problem, null);
  assert.deepEqual(answers, [
    { itemId: 'CF-1', disposition: 'accepted-deviation', reason: 'Generated by the formatter.', clauseIds: [] },
    { itemId: 'CF-2', disposition: 'rework', reason: '', clauseIds: [] }]);
  const summary = adjudicationSummary(list(), answers);
  assert.match(summary, /src\/CF-1\.js: Accept as is\. Reason: Generated by the formatter\./u);
  assert.match(summary, /Still undecided: PAY-1:REQ-001/u);
});

test('the page refuses what would record nothing true', () => {
  const answersOf = (rows) => adjudicationAnswersFrom(list(), { type: 'adjudicate.review', rows });
  assert.match(answersOf([row('CF-1', 'accepted-deviation')]).problem, /Give a reason for src\/CF-1\.js/u);
  assert.match(answersOf([row('CF-1', 'update-intent', 'The spec is wrong.')]).problem, /Name the clauses/u);
  assert.match(answersOf([row('CF-1', '')]).problem, /at least one row/u);
  assert.match(answersOf([row('CF-9', 'rework')]).problem, /not on this list/u);
  assert.match(answersOf([row('CF-1', 'dismiss-everything', 'x')]).problem, /not a decision/u);
  assert.deepEqual(answersOf([row('CF-1', 'update-intent', 'The spec is wrong.', 'PAY-1:REQ-1, PAY-1:REQ-2')]).answers[0].clauseIds, ['PAY-1:REQ-1', 'PAY-1:REQ-2']);
});

test('what a person entered survives a refusal, a cancelled review and a re-read', () => {
  const draft = adjudicationDraftFrom({ type: 'adjudicate.review', rows: [row('CF-1', 'rework', 'Still typing this.', ''), row('CF-3', 'update-intent', '', 'PAY-1:REQ-9')] });
  const html = adjudicationHtml(list(), { error: 'Give a reason.', draft });
  assert.match(html, /<option value="rework" selected>/u);
  assert.match(html, /value="Still typing this\."/u);
  assert.match(html, /value="PAY-1:REQ-9"/u);
  assert.match(html, /role="alert">Give a reason\./u);
});

test('a reason with no decision is asked about, never dropped', () => {
  const { problem, answers } = adjudicationAnswersFrom(list(), { type: 'adjudicate.review', rows: [row('CF-1', 'rework'), row('CF-2', '', 'A reason on an open row.')] });
  assert.deepEqual(answers, []);
  assert.match(problem, /Choose a decision for src\/CF-2\.js, or clear its reason/u);
});

test('the page uses the one VS Code handle every page shares', () => {
  // acquireVsCodeApi works once per page and page() has already called it: a second call stopped this
  // whole script, so no button worked, and only the real app showed it.
  assert.doesNotMatch(ADJUDICATION_SCRIPT, /acquireVsCodeApi/u);
  assert.match(ADJUDICATION_SCRIPT, /window\.__sfVscode/u);
});

test('a list that is not open says why and offers no table', () => {
  const html = adjudicationHtml({ status: 'not-open', workId: 'PAY-1', phase: null, repositoryPath: '/repo', items: [], open: 0, message: 'There is nothing to adjudicate.' });
  assert.match(html, /There is nothing to adjudicate\./u);
  assert.doesNotMatch(html, /<table/u);
  assert.equal(adjudicationListFrom(null), null);
  assert.equal(adjudicationListFrom({ status: 'open' }), null);
});

test('test setup files are one row, whose one decision answers for each by name', () => {
  const setup = (id, file) => item(id, { paths: [file], group: 'test-setup' });
  const grouped = list({ items: [setup('CF-1', 'package-lock.json'), item('CF-2'), setup('CF-3', 'playwright.config.js'), setup('CF-4', 'src/test/setup.js')],
    groupWords: { 'test-setup': 'These changed together for how tests run: one change, so one decision.' } });
  const html = adjudicationHtml(grouped);
  assert.equal(html.match(/<tr data-item=/gu).length, 2, 'one row for the three files, one for the other');
  assert.match(html, /data-item="CF-1" data-accept-all="true" data-group-items="CF-1,CF-3,CF-4"/u);
  assert.match(html, /Test setup<\/strong>[\s\S]*package-lock\.json[\s\S]*playwright\.config\.js[\s\S]*src\/test\/setup\.js[\s\S]*one change, so one decision/u);
  const { answers, problem } = adjudicationAnswersFrom(grouped, { type: 'adjudicate.review', rows: [
    { id: 'CF-1', ids: 'CF-1,CF-3,CF-4', disposition: 'accepted-deviation', reason: 'Adding the browser runner needs these.', clauses: '' }, { id: 'CF-2', ids: '', disposition: '', reason: '', clauses: '' }] });
  assert.equal(problem, null);
  assert.deepEqual(answers.map((answer) => [answer.itemId, answer.disposition, answer.reason]), ['CF-1', 'CF-3', 'CF-4'].map((id) => [id, 'accepted-deviation', 'Adding the browser runner needs these.']));
  assert.match(adjudicationSummary(grouped, answers), /Still undecided: src\/CF-2\.js/u);
  // A page can only answer for files of the same group on the list it read.
  assert.match(adjudicationAnswersFrom(grouped, { rows: [{ id: 'CF-1', ids: 'CF-1,CF-2', disposition: 'accepted-deviation', reason: 'x'.repeat(20), clauses: '' }] }).problem, /not on this list/u);
  assert.match(adjudicationAnswersFrom(grouped, { rows: [{ id: 'CF-2', ids: 'CF-2,CF-3', disposition: 'accepted-deviation', reason: 'x'.repeat(20), clauses: '' }] }).problem, /not on this list/u);
  assert.match(ADJUDICATION_SCRIPT, /ids: row\.dataset\.groupItems/u);
});

test('a row the plan settled can be overruled on the page, through the same answers, with nothing chosen', () => {
  const settled = { id: 'CF-9', paths: ['package.json'], clauseIds: [], settledBy: { kind: 'supporting', text: 'The test script.' }, decision: null };
  const open = list({ items: [], open: 0, settled: [settled] });
  const html = adjudicationHtml(open);
  assert.match(html, /<tr data-item="CF-9" data-settled="CF-9" data-accept-all="false">/u);
  assert.match(html, /<option value="">Keep what the plan says<\/option>/u);
  assert.doesNotMatch(html, /<option [^>]*selected/u, 'keeping the plan is nothing chosen');
  assert.doesNotMatch(html, /run story adjudicate/u, 'disagreeing needs no terminal');
  assert.match(html, /data-review>Review and record/u, 'with nothing open it can still be recorded');
  assert.deepEqual(adjudicationAnswersFrom(open, { type: 'x', rows: [{ id: 'CF-9', disposition: '', reason: '', clauses: '' }] }).answers, [], 'keeping the plan answers nothing');
  const { answers, problem } = adjudicationAnswersFrom(open, { type: 'x', rows: [{ id: 'CF-9', disposition: 'rework', reason: 'It should not have changed.', clauses: '' }] });
  assert.equal(problem, null);
  assert.deepEqual(answers, [{ itemId: 'CF-9', disposition: 'rework', reason: 'It should not have changed.', clauseIds: [] }]);
  assert.match(adjudicationSummary(open, answers), /package\.json: Send back to fix\. Reason: It should not have changed\./u);
  // Someone outside the group is told, and offered no control.
  assert.doesNotMatch(adjudicationHtml({ ...open, decidedBy: { groups: [], labels: [], allowed: false, words: 'The Leads decide these.' } }), /data-disposition/u);
});
