test('protected guards and source boundaries inspect both rename and deletion endpoints',()=>{
  const entries=[{changeId:'moved',status:'R100',oldPath:'src/secret.js',newPath:'test/secret.test.js'},
    {changeId:'removed',status:'D',oldPath:'config/private.yml',newPath:null}];
  assert.deepEqual(native.changeSetPaths({entries}),['config/private.yml','src/secret.js','test/secret.test.js']);
  const protectedPaths=native.evaluateProtectedPaths({entries},['src','config']);
  assert.equal(protectedPaths.valid,false);
  assert.deepEqual(protectedPaths.violations.map(row=>[row.changeId,row.endpoint,row.path]),[
    ['moved','oldPath','src/secret.js'],['removed','oldPath','config/private.yml']]);
  const boundary=native.evaluateSourceBoundary({entries},'test-automation',{allowedPath:native.isTestAutomationPath,phaseId:'repair'});
  assert.equal(boundary.valid,false);
  assert.deepEqual(boundary.violations.map(row=>row.path),['src/secret.js','config/private.yml']);
  assert.deepEqual(native.evaluateSourceBoundary({entries},'unrestricted'),{valid:true,violations:[]});
});

test('case comparison is explicit and changing roots cannot mutate an existing policy binding',()=>{
  const roots=['owned'];
  const policy=rules.applicationPathPolicies(roots);
  roots.push('src');
  assert.equal(policy.isApplicationPath('owned/file.md'),false);
  assert.equal(policy.isApplicationPath('src/file.js'),true);
  assert.equal(policy.isApplicationPath('OWNED/file.md'),true);
  assert.equal(policy.isApplicationPath('OWNED/file.md',{caseInsensitivePaths:true}),false);
  const entry={changeId:'case',status:'M',oldPath:'SRC/App.js',newPath:'SRC/App.js'};
  assert.equal(native.evaluateProtectedPaths({entries:[entry]},['src']).valid,true);
  assert.equal(native.evaluateProtectedPaths({entries:[entry],target:{caseInsensitivePaths:true}},['src']).valid,false);
  for(const roots of [null,{},['../escape'],['/absolute'],['a\\b'],Array(1),Array(129).fill('ok')]){
    assert.throws(()=>rules.applicationPathPolicies(roots));
  }
  let accessed=false;
  const accessor=[];Object.defineProperty(accessor,'0',{enumerable:true,get(){accessed=true;return 'unsafe';}});
  assert.throws(()=>rules.applicationPathPolicies(accessor),{code:'ENGINE_SOURCE_PATH_POLICY_INVALID'});
  assert.equal(accessed,false);
});

test('explicit POSIX and Win32 string primitives preserve the shared portable path decisions on this host',()=>{
  // A grammar test, not native Windows qualification.
  const posix=families(syntax(path.posix)),win32=families(syntax(path.win32));
  for(const {group,method,args}of baseline.cases){
    if(JSON.stringify(args).includes('\\\\'))continue; // Native legacy separator coercion is deliberately host-specific.
    assert.deepEqual(outcome(()=>posix[group][method](...structuredClone(args))),
      outcome(()=>win32[group][method](...structuredClone(args))),`${group}.${method}: ${JSON.stringify(args)}`);
  }
  for(const family of Object.values(win32))assert.equal(Object.isFrozen(family),true);
  for(const name of ['configurationFilePolicies','sourceBoundaryPolicies','supportingChangePolicies','changeScopePolicies']){
    assert.throws(()=>rules[name]({...syntax(path.posix)}),{code:'ENGINE_CONFIGURATION_PATH_SYNTAX_INVALID'});
  }
});
