/** The line a person adds to a hooks directory SFlow does not write: portable, and it fails closed. */
const HOOK_LINE = 'sflow secrets scan --staged || exit 1';

/** `target` with every existing ancestor resolved, so /tmp and /private/tmp compare equal. */
function canonical(target) {
  const missing = [];
  for (let current = path.resolve(target); ; current = path.dirname(current)) {
    try { return path.join(realpathSync.native(current), ...missing.reverse()); }
    catch { /* not there yet: resolve its parent */ }
    if (path.dirname(current) === current) return path.resolve(target);
    missing.push(path.basename(current));
  }
}

function within(child, parent) {
  const relative = path.relative(canonical(parent), canonical(child));
  return relative === '' || (relative !== '..' && !relative.startsWith(`..${path.sep}`) && !path.isAbsolute(relative));
}

const shellQuoted = (value) => `'${String(value).replaceAll("'", "'\\''")}'`;

/**
 * The hooks directory Git itself runs for this checkout, and whether SFlow may write there.
 *
 * `<git-dir>/hooks` was the old answer and it was wrong twice. A linked worktree's private Git
 * directory has a `hooks` folder Git never reads (every worktree runs the common directory's
 * hooks), and with `core.hooksPath` set Git ignores `.git/hooks` entirely. Either way the hook was
 * written, nothing ran it, and the command said commits were protected. `--git-path hooks` is Git's
 * own resolution of both, so the answer cannot drift from what `git commit` does.
 */
function hookLocation(root) {
  const answered = run('git', ['rev-parse', '--git-path', 'hooks'], { cwd: root, allowFailure: true });
  const directory = path.resolve(root, gitReadOutput(answered, 'The hooks directory Git runs').trim());
  const common = gitCommonDir(root);
  const own = gitDir(root);
  const linkedWorktree = canonical(own) !== canonical(common);
  const redirected = canonical(directory) !== canonical(path.join(common, 'hooks'));
  // Inside the repository's Git directory the hook is private to this clone. A directory in the
  // working tree is shared through commits or generated by a hook manager, and one outside the
  // repository belongs to whoever configured it; writing either would change something that is
  // not this checkout's to change.
  const placement = within(directory, common) || within(directory, own) ? 'git-directory'
    : within(directory, root) ? 'working-tree' : 'outside-repository';
  return { directory, hook: path.join(directory, 'pre-commit'), placement, linkedWorktree, redirected, common, own };
}

/** Where `core.hooksPath` was set, as the exact command that removes it, or null when no file holds it. */
function hooksPathUnsetCommand(root, location) {
  const answered = run('git', ['config', '--show-origin', '--get', 'core.hooksPath'], { cwd: root, allowFailure: true });
  const origin = answered.status === 0 ? /^file:(.+)\t/u.exec(answered.stdout ?? '')?.[1] ?? null : null;
  if (!origin || origin.startsWith('"')) return { command: null, origin: answered.status === 0 ? String(answered.stdout).split('\t')[0] : null };
  const file = path.resolve(root, origin);
  if (canonical(file) === canonical(path.join(location.common, 'config'))) return { command: 'git config --unset core.hooksPath', origin: file };
  if (canonical(file) === canonical(path.join(location.own, 'config.worktree'))) return { command: 'git config --worktree --unset core.hooksPath', origin: file };
  return { command: `git config --file ${shellQuoted(file)} --unset core.hooksPath`, origin: file };
}

/** Whether a hook someone else maintains already runs the staged scan: executable, and not commented out. */
function runsSecretScan(hook, text) {
  if (text == null) return false;
  if (process.platform !== 'win32' && !(statSync(hook).mode & 0o111)) return false;
  return text.split(/\r?\n/u).some((line) => !line.trimStart().startsWith('#') && /secrets scan --staged/u.test(line));
}

/**
 * `core.hooksPath` sends Git's hooks somewhere SFlow does not write. Nothing is written, and the
 * result says protection is inactive and names the two ways to make it real — unless the hook Git
 * runs there already calls the scan, which is the one case that is honestly protected.
 */
async function protectionElsewhere(root, location, options) {
  const json = optionBoolean(options, 'json');
  const existing = existsSync(location.hook) ? await readFile(location.hook, 'utf8') : null;
  const base = {
    resultType: 'secret-protection', schemaVersion: 1, hook: location.hook, hooksDirectory: location.directory,
    installed: false, hooksPathConfigured: true, placement: location.placement
  };
  if (runsSecretScan(location.hook, existing)) {
    const result = { ...base, active: true };
    if (!json) console.log(`Git's pre-commit hook at ${location.hook} already runs the secret check. Nothing was written.`);
    emitCommandResult(commandResult({
      operation: { id: 'secrets.protect', classification: 'mutation' },
      outcome: succeeded('secrets.protected-by-hooks-path', { hook: location.hook }),
      effects: noEffects(), restState: 'complete', data: result
    }), { json });
    return result;
  }
  const unset = hooksPathUnsetCommand(root, location);
  const reason = location.placement === 'working-tree' ? 'hooks-path-in-working-tree' : 'hooks-path-outside-repository';
  const code = 'SECRET_HOOK_INACTIVE';
  const manualSteps = [
    { id: 'add-hook-line', file: location.hook, line: HOOK_LINE,
      instruction: `Add \`${HOOK_LINE}\` to ${location.hook} (create it as an executable shell script if it does not exist).` },
    { id: 'unset-hooks-path', command: unset.command, origin: unset.origin,
      instruction: unset.command
        ? `Or stop redirecting Git's hooks with \`${unset.command}\`, then re-run \`singularity-flow secrets protect\`.`
        : `Or remove core.hooksPath where it is set${unset.origin ? ` (${unset.origin})` : ' (a `git -c` option or GIT_CONFIG_* variables)'}, then re-run \`singularity-flow secrets protect\`.` }
  ];
  const result = { ...base, active: false, code, reason, manualSteps };
  const where = location.placement === 'working-tree'
    ? 'a directory in the working tree, shared through commits or generated by a hook manager'
    : 'a directory outside this repository, owned by whoever configured it';
  const error = new SingularityFlowError([
    `Secret protection is not active. core.hooksPath makes Git run hooks from ${location.directory}, ${where}, so Singularity Flow wrote nothing there and \`git commit\` does not check for credentials.`,
    ...manualSteps.map((step) => step.instruction)
  ].join('\n'), { code, exitCode: 2, details: { operation: 'secrets.protect' } });
  throw withCommandResult(error, commandResult({
    operation: { id: 'secrets.protect', classification: 'mutation' },
    outcome: refused('secrets.protection-inactive', { hooksDirectory: location.directory }),
    effects: noEffects(),
    why: [because(`secrets.${reason}`, 'config', { ref: 'core.hooksPath', slots: { hooksDirectory: location.directory } })],
    next: [
      action({ id: 'secrets.scan-staged', label: 'Until the hook is in place, check what is staged before each commit',
        command: 'singularity-flow secrets scan --staged', kind: 'informational' }),
      action({ id: 'secrets.protect-again', label: 'After either manual step, confirm protection is active',
        command: 'singularity-flow secrets protect', rank: 'SOON', kind: 'remediation' })
    ],
    restState: 'informational',
    data: result
  }));
}

async function runSecrets(argv, { positionals, options }) {
  return withCommandObservability(positionals[0], argv, options,
    () => withCommandConfirmation(options, () => secretsCommand(positionals, options)));
}

export { runSecrets as run };

/**
 * `sflow secrets scan` / `sflow secrets protect`.
 *
 * The commit gate refuses without being asked, which is what makes it a control rather than advice.
 * These are the two things a person still needs: to look before they commit, and to extend the same
 * refusal to plain `git commit`, which never enters this CLI at all.
 */
export async function secretsCommand(positionals, options) {
  const subcommand = positionals[1] ?? 'scan';
  if (!SECRETS_SUBCOMMANDS.includes(subcommand)) {
    throw new SingularityFlowError(`Unknown secrets subcommand '${subcommand}'. Use ${SECRETS_SUBCOMMANDS.join(' or ')}.`);
  }
  const root = repoRoot();
  const { configValueWarning, scanEntries, secretRefusal } = await import('../secrets.mjs');

  if (subcommand === 'protect') {
    const location = hookLocation(root);
    const hookPath = location.hook;
    if (location.placement !== 'git-directory') return protectionElsewhere(root, location, options);
    /**
     * A hook, not a wrapper. It runs for `git commit` however it is invoked — terminal, editor,
     * another tool — which is the whole reason it exists; a check that only fires when someone
     * remembers to type a command is documentation.
     *
     * `--staged` matters: the hook must judge what is staged, not what is on disk. A file cleaned in
     * the editor after staging would otherwise pass with the credential still in the index.
     */
    /**
     * Resolve the CLI, do not assume it is on PATH.
     *
     * The first version of this hook was `exec sflow secrets scan --staged`, which failed closed for
     * the wrong reason on any machine where `sflow` was not installed globally: every commit broke
     * with `sflow: not found`, and the developer's only clue pointed at a tool they never installed.
     * Failing closed is right; failing closed illegibly teaches people to pass --no-verify.
     *
     * The CLI that installed the hook wins, and PATH is the fallback. The other order looks more
     * accommodating and is wrong: a stale global `sflow` shadows the one the person actually chose,
     * and if it predates this command every commit is refused with `Unknown command 'secrets'` —
     * observed, not hypothesised. A governance control should run the exact thing it was installed
     * from; picking up upgrades is not worth being at the mercy of whatever is first on PATH.
     */
    // From the package root, not this file: installed copies run this module inside bundle/cli.mjs,
    // one directory up from here, so a path counted from this file would leave the package.
    const installedFrom = path.join(PACKAGE_ROOT, 'bin', 'singularity-flow.mjs');
    const script = [
      '#!/bin/sh',
      '# Installed by `sflow secrets protect`. Refuses a commit containing a credential.',
      '# Bypass in a genuine emergency with `git commit --no-verify`; the commit path',
      '# checks again and cannot be bypassed that way.',
      `if [ -f ${JSON.stringify(installedFrom)} ]; then`,
      `  exec node ${JSON.stringify(installedFrom)} secrets scan --staged`,
      'elif command -v sflow >/dev/null 2>&1; then',
      '  exec sflow secrets scan --staged',
      'else',
      '  echo "singularity-flow: the secret check cannot run — sflow is not on PATH and" >&2',
      `  echo "${installedFrom} is missing. Reinstall, or re-run \\\`sflow secrets protect\\\`." >&2`,
      '  exit 1',
      'fi',
      ''
    ].join('\n');
    const existing = existsSync(hookPath) ? await readFile(hookPath, 'utf8') : null;
    if (existing && !existing.includes('sflow secrets scan') && !optionBoolean(options, 'force')) {
      throw new SingularityFlowError(
        `${hookPath} already exists and was not written by Singularity Flow. `
        + 'Add `sflow secrets scan --staged` to it, or re-run with --force to replace it.',
        { code: 'SECRET_HOOK_EXISTS' }
      );
    }
    await mkdir(path.dirname(hookPath), { recursive: true });
    await writeText(hookPath, script);
    chmodSync(hookPath, 0o755);
    // One hooks directory serves every worktree of the repository, so say so: installing from a
    // linked worktree protects the main checkout and its siblings too.
    const scope = location.linkedWorktree || existsSync(path.join(location.common, 'worktrees')) ? 'all-worktrees' : 'checkout';
    const result = {
      resultType: 'secret-protection', schemaVersion: 1, hook: hookPath, hooksDirectory: location.directory,
      installed: true, active: true, replaced: Boolean(existing), scope, hooksPathConfigured: location.redirected
    };
    const narration = commandResult({
      operation: { id: 'secrets.protect', classification: 'mutation' },
      outcome: succeeded('secrets.protected', { hook: hookPath }),
      effects: effects({ filesChanged: true }),
      restState: 'informational',
      data: result
    });
    if (!optionBoolean(options, 'json')) {
      console.log(`\`git commit\` now refuses a commit containing a credential${scope === 'all-worktrees' ? ', in every worktree of this repository' : ''}.`);
    }
    emitCommandResult(narration, { json: optionBoolean(options, 'json') });
    return result;
  }

  // `--staged` judges the index, which is what a commit will use. Without it, the working tree.
  const staged = optionBoolean(options, 'staged');
  const output = run('git', staged ? ['diff', '--cached', '--name-status', '-z', '--diff-filter=ACMRT'] : ['ls-files', '-z'], { cwd: root }).stdout.split('\0').filter(Boolean);
  const listed = [], added = [];
  if (!staged) listed.push(...output);
  // `A path`, `M path`, and `R100 old new`: a rename or a copy adds its second path.
  else for (let index = 0; index < output.length; index += 1) {
    const status = output[index];
    if (/^[RC]/u.test(status)) index += 1;
    const file = output[++index];
    listed.push(file);
    if (/^[ACR]/u.test(status)) added.push(file);
  }

  const entries = [];
  if (staged) {
    entries.push(...stagedEntriesForPaths(root, listed, { label: 'secrets.scan staged blobs' }));
  } else {
    for (const item of listed) {
      try { entries.push({ path: item, content: await readFile(path.resolve(root, item), 'utf8') }); }
      catch (error) { if (error?.code !== 'ENOENT') entries.push({ path: item }); }
    }
  }

  // A name refuses what a commit adds, unless a person classified it as shared. A file already tracked is
  // read as shared config, and `env audit` asks for its class.
  const { alwaysLocalName, classifiedShared } = await import('../local-config-policy.mjs');
  const alwaysLocal = added.filter((item) => alwaysLocalName(item) && !classifiedShared(entries.find((entry) => entry.path === item)?.content));
  const { scanAgainstGit } = await import('../git.mjs');
  const scan = alwaysLocal.length ? scanEntries(entries, { alwaysLocal }) : staged ? scanAgainstGit(root, entries) : scanEntries(entries);
  const scope = staged ? 'staged' : 'tracked';
  const slots = { scanned: scan.scanned, scope, blocking: scan.blocking.length, warnings: scan.warnings.length };
  const narration = commandResult({
    operation: { id: 'secrets.scan', classification: 'read' },
    // A scan that finds something has not failed — it did its job. `noop` with the detected message
    // keeps "the command worked" and "the commit must not proceed" as separate facts; the exit code
    // below is what stops the commit.
    outcome: scan.blocking.length ? noop('secrets.detected', slots) : scan.warnings.length ? noop('secrets.warned', slots) : succeeded('secrets.clean', slots),
    effects: noEffects(),
    restState: 'informational',
    data: { ...scan, scope }
  });
  if (!optionBoolean(options, 'json')) {
    // The detail goes to stderr, where the pre-commit hook shows it, and where it cannot be piped
    // into something that records it by accident.
    const refusal = secretRefusal(scan);
    const warning = configValueWarning(scan.warnings);
    if (warning) console.error(warning);
    if (refusal) console.error(refusal);
    else if (scan.waived.length) console.log(`${scan.waived.length} waived finding(s) were allowed.`);
  }
  emitCommandResult(narration, { json: optionBoolean(options, 'json') });
  // Non-zero so the pre-commit hook refuses, and so CI does.
  if (scan.blocking.length) process.exitCode = 1;
  return scan;
}
